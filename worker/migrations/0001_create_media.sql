-- Media metadata. The R2 object key is always derived server-side (media/{id});
-- nothing in this table is used as a key without coming from the Worker itself.
CREATE TABLE media (
  id            TEXT PRIMARY KEY,                         -- UUID v4 generated by the Worker
  object_key    TEXT NOT NULL UNIQUE,                     -- 'media/' || id
  owner_sub     TEXT NOT NULL,                            -- Auth0 `sub` of the uploader
  original_name TEXT NOT NULL,                            -- sanitized, display only
  content_type  TEXT NOT NULL,                            -- from the server allowlist
  size_bytes    INTEGER NOT NULL CHECK (size_bytes > 0),
  status        TEXT NOT NULL CHECK (status IN ('pending', 'ready')),
  created_at    TEXT NOT NULL,                            -- ISO-8601 UTC
  completed_at  TEXT,
  CHECK (object_key = 'media/' || id)
);

CREATE INDEX idx_media_status_created ON media (status, created_at DESC, id DESC);
CREATE INDEX idx_media_owner ON media (owner_sub);
