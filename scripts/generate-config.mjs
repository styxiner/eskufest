#!/usr/bin/env node
/**
 * Generates src/app/core/config/app-config.generated.ts from environment variables.
 *
 * All of these values end up in the public JS bundle: they are configuration,
 * NOT secrets. Never add a secret here.
 *
 *   AUTH0_DOMAIN     Auth0 (custom) domain, host only, e.g. auth.example.com
 *   AUTH0_CLIENT_ID  Public client id of the Auth0 SPA application
 *   AUTH0_AUDIENCE   Identifier of the Auth0 API that represents the Worker
 *   API_URL          Base URL of the Worker API, e.g. https://api.album.example.com
 *
 * Values are read from process.env, falling back to a local `.env` file (gitignored).
 *
 * --strict  fail if any value is missing/invalid (used for production builds).
 * Without --strict, missing values are replaced by obviously invalid placeholders so
 * that lint/tests/dev builds work without a real tenant.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = resolve(root, 'src/app/core/config/app-config.generated.ts');
const strict = process.argv.includes('--strict');

const envFile = resolve(root, '.env');
if (existsSync(envFile)) {
  process.loadEnvFile(envFile);
}

const HOSTNAME = /^(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/i;

function isHttpsUrl(value) {
  try {
    const url = new URL(value);
    const localDev = url.protocol === 'http:' && ['localhost', '127.0.0.1'].includes(url.hostname);
    return (url.protocol === 'https:' || (!strict && localDev)) && !url.search && !url.hash;
  } catch {
    return false;
  }
}

const fields = {
  AUTH0_DOMAIN: { key: 'auth0Domain', valid: (v) => HOSTNAME.test(v), placeholder: 'auth0-domain.invalid' },
  AUTH0_CLIENT_ID: { key: 'auth0ClientId', valid: (v) => /^[A-Za-z0-9_-]{10,128}$/.test(v), placeholder: 'placeholder-client-id' },
  AUTH0_AUDIENCE: { key: 'auth0Audience', valid: (v) => v.length > 0 && v.length <= 512, placeholder: 'https://api.invalid' },
  API_URL: { key: 'apiUrl', valid: isHttpsUrl, placeholder: 'https://api.invalid' },
};

const config = {};
const problems = [];
for (const [name, { key, valid, placeholder }] of Object.entries(fields)) {
  const raw = (process.env[name] ?? '').trim();
  if (raw && valid(raw)) {
    config[key] = key === 'apiUrl' ? raw.replace(/\/+$/, '') : raw;
  } else {
    problems.push(`${name} is ${raw ? 'invalid' : 'missing'}`);
    config[key] = placeholder;
  }
}

if (problems.length > 0) {
  const message = `[generate-config] ${problems.join('; ')}`;
  if (strict) {
    console.error(`${message}. Refusing to build with placeholder configuration.`);
    process.exit(1);
  }
  console.warn(`${message}. Using placeholders (the app will not be able to log in).`);
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/generate-config.mjs. Do not edit, do not commit.\n` +
    `// Public configuration only: this file is shipped in the browser bundle.\n` +
    `import type { AppConfig } from './app-config';\n\n` +
    `export const GENERATED_APP_CONFIG: AppConfig = ${JSON.stringify(config, null, 2)};\n`,
);
console.log(`[generate-config] wrote ${outFile}`);
